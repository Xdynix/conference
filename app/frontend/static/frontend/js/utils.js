(function () {
  "use strict";

  const ULID_PLACEHOLDERS = [
    "00000000000000000000000001",
    "00000000000000000000000002",
    "00000000000000000000000003",
  ];

  /**
   * Creates a URL builder function from a template with placeholders.
   *
   * Supports two placeholder formats:
   * - Named: `__PARAM_NAME__` for string params (e.g., conference names)
   * - Positional: ULID placeholders for ULID params (use "ulid" as param name)
   *
   * @param {string} template - URL template with placeholders.
   * @param {...string} paramNames - Parameter names matching placeholders (in order).
   *   Use "ulid" for ULID placeholders generated by {% ulid_placeholder N %}.
   * @returns {function(...string): string} Function that builds the URL.
   *
   * @example
   * // Named placeholder
   * const getConference = urlTemplate(
   *   "/api/v1/conferences/__CONFERENCE_NAME__/",
   *   "conference_name"
   * );
   * getConference("icse-2025")  // "/api/v1/conferences/icse-2025/"
   *
   * @example
   * // ULID placeholder
   * const getPaper = urlTemplate(
   *   "/api/v1/papers/00000000000000000000000001/",
   *   "ulid"
   * );
   * getPaper("01ARZ3NDEKTSV4RRFFQ69G5FAV")
   *
   * @example
   * // Mixed placeholders
   * const getPaper = urlTemplate(
   *   "/api/v1/conferences/__CONFERENCE_NAME__/papers/00000000000000000000000001/",
   *   "conference_name", "ulid"
   * );
   * getPaper("icse-2025", "01ARZ3NDEKTSV4RRFFQ69G5FAV")
   *
   * @example
   * // Multiple ULIDs
   * const getReview = urlTemplate(
   *   "/api/v1/papers/00000000000000000000000001/reviews/00000000000000000000000002/",
   *   "ulid", "ulid"
   * );
   * getReview("01ARZ3NDEKTSV4RRFFQ69G5FAV", "01BRZ3NDEKTSV4RRFFQ69G5FAV")
   */
  function urlTemplate(template, ...paramNames) {
    return (...values) => {
      let url = template;
      let ulidIndex = 0;
      paramNames.forEach((name, i) => {
        if (name === "ulid") {
          url = url.replace(ULID_PLACEHOLDERS[ulidIndex++], encodeURIComponent(values[i]));
        } else {
          url = url.replace(`__${name.toUpperCase()}__`, encodeURIComponent(values[i]));
        }
      });
      return url;
    };
  }

  /**
   * Maps API validation errors to field-keyed error messages.
   *
   * Extracts the field path from `loc` after stripping common prefixes like "body" and
   * "payload", and filtering out Pydantic internal type descriptors. Nested paths are
   * joined with dots. Multiple errors for the same field are joined with a space.
   *
   * For example:
   *   [{loc: ["body", "payload", "password"], msg: "Too short."},
   *    {loc: ["body", "payload", "password"], msg: "Too common."}]
   * becomes:
   *   {password: "Too short. Too common."}
   *
   * Nested fields with array indices:
   *   [{loc: ["body", "payload", "authors", 0, "given_name"], msg: "Required."}]
   * becomes:
   *   {"authors.0.given_name": "Required."}
   *
   * Pydantic type descriptors are filtered:
   *   [{loc: ["body", "payload", "email", "literal['']"], msg: "..."}]
   * becomes:
   *   {"email": "..."}
   *
   * @param {Array<{loc: (string|number)[], msg: string}>} details - API error details.
   * @returns {Object<string, string>} Field-keyed error messages.
   */
  function mapErrors(details) {
    const prefixes = new Set(["body", "payload"]);
    // Skip unhelpful messages from Pydantic union type alternatives.
    const skipPatterns = [/^Input should be '.*'$/];

    const result = {};
    for (const error of details || []) {
      const loc = error.loc || [];

      const fieldParts = loc.filter((part) => {
        if (typeof part === "number") return true;
        if (prefixes.has(part)) return false;
        // Filter out Pydantic internal type descriptors (contain brackets or pipes).
        if (part.includes("[") || part.includes("|")) return false;
        return true;
      });
      const field = fieldParts.join(".") || "_form";

      let msg = error.msg;
      // Skip unhelpful messages.
      if (skipPatterns.some((p) => p.test(msg))) continue;
      // Clean up verbose email validation prefix.
      if (field.endsWith(".email") || field === "email") {
        msg = msg.replace(/^value is not a valid email address:\s*/i, "");
      }

      if (result[field]) {
        result[field] += " " + msg;
      } else {
        result[field] = msg;
      }
    }
    return result;
  }

  /**
   * Gets a value from an object using a dot-separated path.
   *
   * @param {object} obj - The object to read from.
   * @param {string} path - Dot-separated path, e.g. "form.email".
   * @returns {*} The value at the path, or undefined if not found.
   */
  function getModelValue(obj, path) {
    return path.split(".").reduce((o, key) => o?.[key], obj);
  }

  /**
   * Sets a value on an object using a dot-separated path.
   *
   * @param {object} obj - The object to modify.
   * @param {string} path - Dot-separated path, e.g. "form.email".
   * @param {*} value - The value to set.
   */
  function setModelValue(obj, path, value) {
    const keys = path.split(".");
    const last = keys.pop();
    const target = keys.reduce((o, key) => o[key], obj);
    target[last] = value;
  }

  /**
   * Extracts the URL hash fragment and optionally clears it from the address bar.
   *
   * @param {boolean} [clear=true] - Whether to clear the hash from the URL.
   * @returns {string} The hash value without the leading "#", or empty string if none.
   */
  function extractUrlHash(clear = true) {
    const hash = window.location.hash.slice(1);
    if (hash && clear) {
      history.replaceState(null, "", window.location.pathname + window.location.search);
    }
    return hash;
  }

  /**
   * Returns a safe redirect URL, validating that it's same-origin.
   *
   * @param {string|null} next - The requested redirect URL.
   * @param {string} fallback - The fallback URL if next is invalid or missing.
   * @returns {string} A safe same-origin URL to redirect to.
   */
  function safeRedirectUrl(next, fallback) {
    if (next) {
      try {
        const url = new URL(next, window.location.origin);
        if (url.origin === window.location.origin) {
          return url.pathname + url.search + url.hash;
        }
      } catch {
        // Invalid URL, ignore.
      }
    }
    return fallback;
  }

  /**
   * Looks up an enum label by its value.
   *
   * @param {Object} enumObj - Enum object from APP.enums (e.g., APP.enums.InvitationState).
   * @param {string} value - The enum value to look up.
   * @returns {string|undefined} The label for the value, or undefined if not found.
   */
  function enumLabel(enumObj, value) {
    return Object.values(enumObj).find((e) => e.value === value)?.label;
  }

  const dateFmt = {
    day: new Intl.DateTimeFormat("en-US", {day: "numeric"}),
    monthYear: new Intl.DateTimeFormat("en-US", {month: "long", year: "numeric"}),
    full: new Intl.DateTimeFormat("en-US", {
      day: "numeric",
      month: "short",
      year: "numeric"
    }),
  };

  /**
   * Formats a date range for display.
   *
   * Handles various cases:
   * - Same month/year: "11-13 January 2026"
   * - Different months: "11 Jan 2026 - 13 Feb 2026"
   * - Only start or end date: "11 Jan 2026"
   * - No dates: ""
   *
   * @param {string|null} startStr - ISO date string for start date.
   * @param {string|null} endStr - ISO date string for end date.
   * @returns {string} Formatted date range.
   */
  function formatDateRange(startStr, endStr) {
    const start = startStr ? new Date(startStr) : null;
    const end = endStr ? new Date(endStr) : null;

    if (start && end) {
      const sameMonthYear =
        start.getMonth() === end.getMonth() &&
        start.getFullYear() === end.getFullYear();
      if (sameMonthYear) {
        return `${dateFmt.day.format(start)}-${dateFmt.day.format(end)} ${dateFmt.monthYear.format(start)}`;
      }
      return `${dateFmt.full.format(start)} - ${dateFmt.full.format(end)}`;
    }
    if (start) return dateFmt.full.format(start);
    if (end) return dateFmt.full.format(end);
    return "";
  }

  /**
   * Formats a file size in bytes to a human-readable string.
   *
   * @param {number} bytes - File size in bytes.
   * @returns {string} Formatted size (e.g., "1.5 MB", "500 KB").
   */
  function formatFileSize(bytes) {
    if (bytes === 0) return "0 B";
    const units = ["B", "KB", "MB", "GB"];
    const i = Math.floor(Math.log(bytes) / Math.log(1024));
    const size = bytes / Math.pow(1024, i);
    return (i === 0 ? size : size.toFixed(1).replace(/\.0$/, "")) + " " + units[i];
  }

  /**
   * Validates a file against upload constraints.
   *
   * @param {File} file - The file to validate.
   * @param {{maxSize: number, allowedTypes: string[]}} config - Upload config
   *   from APP.config.upload (e.g., APP.config.upload.submission).
   * @returns {string|null} Error message if invalid, null if valid.
   */
  function validateFile(file, config) {
    const {maxSize, allowedTypes} = config;

    if (file.size > maxSize) {
      return `File too large. Maximum size is ${formatFileSize(maxSize)}.`;
    }

    const ext = "." + file.name.split(".").pop().toLowerCase();
    if (!allowedTypes.includes(ext)) {
      const types = allowedTypes.map((t) => t.slice(1).toUpperCase()).join(", ");
      return `Invalid file type. Allowed: ${types}.`;
    }

    return null;
  }

  window.urlTemplate = urlTemplate;
  window.mapErrors = mapErrors;
  window.getModelValue = getModelValue;
  window.setModelValue = setModelValue;
  window.extractUrlHash = extractUrlHash;
  window.safeRedirectUrl = safeRedirectUrl;
  window.enumLabel = enumLabel;
  window.formatDateRange = formatDateRange;
  window.formatFileSize = formatFileSize;
  window.validateFile = validateFile;
})();
